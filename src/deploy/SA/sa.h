#ifndef SA_H
#define SA_H

#include "cell.h"
#include "grid.h"
#include "trace.h"
#include "metric.h"

#define MAX_NUMBER_OF_RSUS 2500
#define MAX_NUMBER_OF_CANDIDATE_CELLS (MAX_CELL_GRID_WIDTH * MAX_CELL_GRID_HEIGHT)


/*
 * Current RSU deployment.
 */
typedef struct deployment_
{
    struct_cell rsus[MAX_NUMBER_OF_RSUS];

    int size;

} struct_deployment;


/*
 * Current state of the simulated annealing search.
 *
 * The candidate cells are partitioned into:
 *
 *     deployment
 *     available
 *
 * Therefore:
 *
 *     deployment.size + available_size = number of candidate cells
 *
 * A neighbor is generated by swapping one element
 * between the two arrays.
 */
typedef struct sa_state_
{
    struct_deployment deployment;

    struct_cell available[MAX_NUMBER_OF_CANDIDATE_CELLS];

    int available_size;

} struct_sa_state;


typedef struct sa_config_
{
    int number_of_iterations;

    double initial_temperature;
    double cooling_rate;

    double alpha;

} struct_sa_config;


typedef struct sa_result_
{
    struct_deployment best_solution;

    double best_objective;

    int number_of_iterations;

    double *temperature_history;
    double *objective_history;
    double *best_objective_history;

    double *current_satisfaction_history[MAX_NUMBER_OF_CLUSTERS];
    double *best_satisfaction_history[MAX_NUMBER_OF_CLUSTERS];

} struct_sa_result;


/*
 * Run simulated annealing for a fixed number of RSUs.
 *
 * candidate_cells contains every valid cell where an RSU
 * may be deployed.
 */
int sa_optimize(
    const struct_trace *trace,
    const int vehicle_clusters[],
    const struct_cell candidate_cells[],
    const int number_of_candidate_cells,
    const int number_of_rsus,
    const double N_required[],
    const double Tn_required[],
    const struct_sa_config config,
    const unsigned int seed,
    struct_sa_result *output_result,
    char *error_msg
);


void sa_result_free(struct_sa_result *result);


#endif